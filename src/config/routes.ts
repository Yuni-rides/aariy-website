export const routes = {
  home: () => "/",
  collection: (slug: string) => `/collections/${slug}`,
  category: (path: string[]) => `/categories/${path.join("/")}`,
  brands: () => "/brands",
  brand: (slug: string) => `/brands/${slug}`,
  brandCollections: (slug: string) => `/brands/${slug}/collections`,
  product: (slug: string) => `/products/${slug}`,
  search: (q?: string) =>
    q ? `/search?q=${encodeURIComponent(q)}` : "/search",
  cart: () => "/cart",
  wishlist: () => "/wishlist",
  checkout: () => "/checkout",
  checkoutSuccess: (orderNumber: string) =>
    `/checkout/success?order=${encodeURIComponent(orderNumber)}`,
  login: (next?: string) =>
    next ? `/login?next=${encodeURIComponent(next)}` : "/login",
  account: () => "/account",
  orders: () => "/account/orders",
  order: (orderNumber: string) => `/account/orders/${orderNumber}`,
  orderReturn: (orderNumber: string) => `/account/orders/${orderNumber}/return`,
  contact: () => "/contact",
  sellerRegister: () => "/become-a-seller",
  policy: (slug: string) => `/policies/${slug}`,
} as const;
